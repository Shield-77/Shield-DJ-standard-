"""Build small, tiled GPU assets; originals remain in assets/ unchanged.

Run with Python + Pillow. The generated header is committed/distributed so
the normal devkitPro build does not need Python on the target machine.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]

def morton(x, y):
    return sum(((x >> b) & 1) << (2*b) | ((y >> b) & 1) << (2*b+1)
               for b in range(3))

def pack(name, filename, size):
    image = Image.open(ROOT / 'assets' / filename).convert('RGBA')
    image.thumbnail((size, size), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (size, size))
    canvas.paste(image, ((size-image.width)//2, (size-image.height)//2))
    data = bytearray(size*size*4)
    for y in range(size):
        for x in range(size):
            i = (((y//8)*(size//8)+x//8)*64 + morton(x & 7, y & 7))*4
            r,g,b,a = canvas.getpixel((x,y))
            data[i:i+4] = bytes((a,b,g,r))
    lines = [f'static const unsigned char {name}[{len(data)}] = {{']
    lines += ['    '+','.join(f'0x{v:02x}' for v in data[i:i+24])+','
              for i in range(0,len(data),24)]
    return '\n'.join(lines+['};'])

out = '// Generated by tools/pack_ui_assets.py. PICA RGBA8 (ABGR bytes).\n#pragma once\n'
out += pack('shield_logo_data','shield-logo.png',64)+'\n'
out += pack('shield_boot_data','boot-source.png',256)+'\n'
(ROOT/'include'/'ui_assets.h').write_text(out,encoding='utf-8')
print('Packed logo: 16 KiB; boot: 256 KiB (released after startup).')
